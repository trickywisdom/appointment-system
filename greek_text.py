# Ελληνικά ονόματα ημερών/μηνών, ΑΝΕΞΑΡΤΗΤΑ από το locale του συστήματος. Το strftime με
# %A/%a/%b διαβάζει το LC_TIME: η set_greek_locale() του gui.py απλώς ΔΟΚΙΜΑΖΕΙ να το
# θέσει και, αν το ελληνικό locale δεν είναι εγκατεστημένο, τυπώνει προειδοποίηση και
# συνεχίζει — οπότε οι ίδιες γραμμές θα εμφάνιζαν «Thursday» μέσα σε ελληνικό UI, ή θα το
# έστελναν στο inbox του πελάτη. Οι τιμές εδώ είναι ίδιες byte-προς-byte με ό,τι παράγει
# το ελληνικό locale των Windows, ώστε η εμφάνιση να μην αλλάξει καθόλου. Τα ΑΡΙΘΜΗΤΙΚΑ
# directives (%d %m %Y %H %M) δεν εξαρτώνται από το locale και μένουν ως έχουν.

